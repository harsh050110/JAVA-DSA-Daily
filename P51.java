public class P51 {
    public static void main(String[] args) {
        int i =9;
        while(i!=0){
            if(i%2==0){
                System.out.print("9 is not a prime number.");
            }else{
                System.out.print("9 is a prime number.");
            }
            break;
        }
        System.out.println();
    }
    
}
