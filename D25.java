public class D25 {
    public static void main(String[] args){
        int time = 2;

        switch(time){
            case 1:
                System.out.println("7AM to 10AM - Breakfast Time");
                break;
                case 2:
                System.out.println("10AM to 12PM - Brunch Time");
                break;
                case 3:
                System.out.println("12PM to 3PM - Lunch Time");
                break;
                case 4:
                System.out.println("3Pm to 5PM - Tea Time");
                break;
                case 5:
                System.out.println("5PM to 8PM - Dinner Time");
                break;
                default:
                System.out.println("Invalid Time");
        }
    }
    
}
